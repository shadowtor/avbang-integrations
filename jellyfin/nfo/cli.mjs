// AVBang NFO generator for Jellyfin (and Emby/Kodi), phase 28.1 D-02. Dependency-free Node >= 20.
//
//   AVBANG_API_KEY=av_live_... node cli.mjs --root /media/movies [--poster|--no-poster] [--force] [--dry-run]
//
// For each video under --root it resolves the filename through GET /v1/match, reads /v1/titles/{code}
// and /v1/titles/{code}/images, and writes '<video name>.nfo' (plus a poster) beside the file.
//
// Key hygiene: the key is read from AVBANG_API_KEY only. It is never printed, never written to disk
// and never placed in an NFO. Do not put it in a crontab line; load it from a protected env file.
// Schedule it with cron or Windows Task Scheduler; runs are idempotent (existing NFO files are skipped).
//
// POSTERS (D-06): this tool DOWNLOADS the poster bytes itself from the signed image URL (valid ~15
// minutes) and WRITES a poster file ('<video name>-poster.<ext>') into your media folder beside the
// video, where it stays on disk until you delete it. Jellyfin also keeps its own copy of images it
// reads. The CLI keeps no cache and never stores the URL. Use --no-poster to avoid writing images.
// The default is the exported POSTER_DEFAULT below.
//
// Safety: only files it generated (uniqueid type avbang) are replaced, and only with --force;
// existing posters are never overwritten; it never deletes; symlinks are not followed.
import { lstat, open, readdir, readFile, realpath, rename, rm } from "node:fs/promises";
import { basename, isAbsolute, join, relative, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { createApiClient } from "../../lib/api-client.mjs";
import { CODE_RE, VIDEO_EXT, buildNfo, extForContentType, isGenerated, nfoName, posterName } from "./nfo.mjs";

/** Owner-flippable default for writing posters. */
export const POSTER_DEFAULT = true;

const IMAGE_HOSTS = ["avbang.net"];
const FATAL = new Set(["network", "rate_limited"]);

class UsageError extends Error {}

function parseArgs(argv) {
  const a = { root: null, apiBase: null, force: false, allowBlurred: false, poster: null, limit: Infinity, dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    const f = argv[i];
    const val = () => {
      const v = argv[++i];
      if (v === undefined || v.startsWith("--")) throw new UsageError(`${f} needs a value`);
      return v;
    };
    if (f === "--root") a.root = val();
    else if (f === "--api-base") a.apiBase = val();
    else if (f === "--limit") {
      const n = Number(val());
      if (!Number.isInteger(n) || n < 1) throw new UsageError("--limit must be a positive integer");
      a.limit = n;
    } else if (f === "--force") a.force = true;
    else if (f === "--allow-blurred") a.allowBlurred = true;
    else if (f === "--dry-run") a.dryRun = true;
    else if (f === "--poster" || f === "--no-poster") {
      const want = f === "--poster";
      if (a.poster !== null && a.poster !== want) throw new UsageError("--poster and --no-poster cannot be used together");
      a.poster = want;
    } else throw new UsageError(`unknown argument ${f}`);
  }
  if (!a.root) throw new UsageError("--root is required");
  return a;
}

/** Recursively list video files. Symlinks (files and directories) are skipped, never followed. */
async function* walk(dir) {
  const entries = (await readdir(dir, { withFileTypes: true })).sort((x, y) => (x.name < y.name ? -1 : 1));
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) yield* walk(p);
    else if (e.isFile() && VIDEO_EXT.has(e.name.slice(e.name.lastIndexOf(".")).toLowerCase())) yield p;
  }
}

async function exists(p) {
  try {
    await lstat(p);
    return true;
  } catch {
    return false;
  }
}

/** Create a new file; fails if anything (including a symlink) already sits at the path. */
async function createNew(path, data) {
  const fh = await open(path, "wx", 0o644);
  try {
    await fh.writeFile(data);
  } finally {
    await fh.close();
  }
}

/** Replace a regular file we generated: temp file then rename, so a symlink is never written through. */
async function replaceGenerated(path, data) {
  const st = await lstat(path);
  if (!st.isFile()) return "not a regular file";
  if (!isGenerated(await readFile(path, "utf8"))) return "existing NFO was not generated by this tool";
  const tmp = `${path}.avbang-tmp-${process.pid}`;
  await createNew(tmp, data);
  try {
    await rename(tmp, path);
  } catch (e) {
    await rm(tmp, { force: true });
    throw e;
  }
  return null;
}

function pickPoster(list, allowBlurred) {
  const imgs = Array.isArray(list?.images) ? list.images : [];
  const ok = imgs.filter((i) => i.access === "clear" || (allowBlurred && i.access === "blurred"));
  const img = ok.find((i) => i.kind === "cover_front") ?? ok[0];
  if (!img) return { reason: imgs.length ? "only blurred images (use --allow-blurred)" : "no image" };
  const u = (img.urls ?? []).find((x) => x.width === 640) ?? img.urls?.[0];
  return u?.url ? { url: u.url } : { reason: "no image url" };
}

/**
 * Main entry, injectable for tests. Returns { code, counts }. Exit code 1 only for configuration or transport failure.
 * deps: { createClient, out }
 */
export async function runCli(argv, env = process.env, deps = {}) {
  const out = deps.out ?? ((l) => console.log(l));
  const createClient = deps.createClient ?? createApiClient;
  const counts = { written: 0, posters: 0, skipped: 0, failed: 0 };
  const skips = [];
  try {
    const args = parseArgs(argv);
    const key = env.AVBANG_API_KEY;
    if (!key) throw new UsageError("AVBANG_API_KEY is not set");
    if (!/^[\x21-\x7e]+$/.test(key)) throw new UsageError("AVBANG_API_KEY has invalid characters");
    const posterOn = args.poster ?? POSTER_DEFAULT;

    const insecure = env.AVBANG_ALLOW_INSECURE === "1";
    // HARNESS ONLY: exact mock image origins, honoured only with the insecure flag outside production.
    const testImageOrigins =
      insecure && env.NODE_ENV !== "production" && env.AVBANG_TEST_IMAGE_ORIGINS
        ? env.AVBANG_TEST_IMAGE_ORIGINS.split(",").map((s) => s.trim()).filter(Boolean)
        : [];
    let client;
    try {
      client = createClient({
        baseUrl: args.apiBase ?? env.AVBANG_API_BASE ?? "https://api.avbang.net/v1",
        key,
        perMinute: 200,
        allowInsecure: insecure,
        testImageOrigins,
      });
    } catch (e) {
      throw new UsageError(String(e.message).replace(key, "[key]"));
    }

    let root;
    try {
      root = await realpath(args.root);
      if (!(await lstat(root)).isDirectory()) throw new Error();
    } catch {
      throw new UsageError("--root is not a readable directory");
    }

    let seen = 0;
    for await (const video of walk(root)) {
      if (seen >= args.limit) break;
      seen++;
      const rel = relative(root, video);
      if (rel.startsWith("..") || isAbsolute(rel)) continue; // containment: never leaves --root
      const label = rel.split(sep).join("/");
      const skip = (why) => {
        counts.skipped++;
        skips.push(`${label}: ${why}`);
      };
      try {
        const nfoPath = nfoName(video);
        const nfoExists = await exists(nfoPath);
        if (nfoExists && !args.force) {
          skip("NFO exists");
          continue;
        }
        const { matches } = await client.get("/v1/match", { filename: label.replace(/[\u0000-\u001f\u007f]/g, " ").slice(-512) });
        const hit = Array.isArray(matches) && matches.length === 1 ? matches[0] : null;
        if (!hit) {
          skip(matches?.length > 1 ? "ambiguous match" : "no match");
          continue;
        }
        if (hit.confidence !== "code" || !CODE_RE.test(String(hit.code))) {
          skip("match not confident");
          continue;
        }
        const code = encodeURIComponent(hit.code);
        const title = await client.get(`/v1/titles/${code}`);
        const xml = buildNfo(title);

        if (args.dryRun) {
          out(`would write ${label} -> ${basename(nfoPath)} (${hit.code})`);
          continue;
        }
        const refused = nfoExists ? await replaceGenerated(nfoPath, xml) : await createNew(nfoPath, xml).then(() => null);
        if (refused) {
          skip(refused);
          continue;
        }
        counts.written++;

        if (posterOn) {
          const pick = pickPoster(await client.get(`/v1/titles/${code}/images`), args.allowBlurred);
          let why = pick.reason;
          if (pick.url) {
            try {
              const img = await client.rawFetchImage(pick.url, IMAGE_HOSTS);
              const ext = extForContentType(img.contentType);
              if (!ext) why = `unsupported image type ${img.contentType}`;
              else {
                await createNew(posterName(video, ext), img.bytes);
                counts.posters++;
              }
            } catch (e) {
              why = e.code === "EEXIST" ? "poster file exists" : e.name === "ApiError" ? e.message : "poster write failed";
            }
          }
          if (why) skips.push(`${label}: poster skipped (${why})`);
        }
      } catch (e) {
        if (e?.name === "ApiError" && (FATAL.has(e.code) || e.status === 401 || e.status === 403)) throw e;
        counts.failed++;
        skips.push(`${label}: failed (${e?.name === "ApiError" ? e.message : "error"})`);
      }
    }
    for (const s of skips) out(s);
    out(`written ${counts.written}, posters ${counts.posters}, skipped ${counts.skipped}, failed ${counts.failed}`);
    return { code: 0, counts };
  } catch (e) {
    const msg = e instanceof UsageError ? e.message : e?.name === "ApiError" ? e.message : "unexpected error";
    out(`error: ${msg}`);
    return { code: 1, counts };
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = (await runCli(process.argv.slice(2))).code;
}
